/**
 * Phase 18.2 - Description auto-population policy for Bank Receipt rows.
 *
 * A row keeps a `descriptionAuto` flag. While the flag is true the cell belongs
 * to the allocation flow and follows the currently allocated bills. As soon as
 * the user types their own text the row becomes manual and the allocation flow
 * never overwrites it again. Everything here is pure so the policy can be
 * tested without React or the DOM.
 */

export const BILL_DESCRIPTION_PREFIX = 'Bill No:';

export const RECEIPT_DESCRIPTION_MAX_LENGTH = 200;

export interface ReceiptDescriptionState {
  description: string;
  descriptionAuto: boolean;
}

const cleanBillNumber = (value: string | null | undefined): string => (value ?? '').trim();

/** True when the text looks like a description generated by this module. */
export const isGeneratedBillDescription = (value: string | null | undefined): boolean =>
  cleanBillNumber(value).startsWith(BILL_DESCRIPTION_PREFIX);

/**
 * Builds `Bill No: A, B` from the bill numbers that received a genuine positive
 * allocation. Blank and duplicate numbers are dropped and an empty list yields
 * an empty string, so a reference is never fabricated.
 */
export const buildBillDescription = (billNumbers: Array<string | null | undefined>): string => {
  const unique: string[] = [];
  for (const value of billNumbers) {
    const billNumber = cleanBillNumber(value);
    if (billNumber === '' || unique.includes(billNumber)) continue;
    unique.push(billNumber);
  }
  if (unique.length === 0) return '';

  let text = BILL_DESCRIPTION_PREFIX;
  let included = 0;
  for (const billNumber of unique) {
    const candidate = included === 0 ? `${text} ${billNumber}` : `${text}, ${billNumber}`;
    if (candidate.length > RECEIPT_DESCRIPTION_MAX_LENGTH) break;
    text = candidate;
    included += 1;
  }
  return included === 0 ? '' : text;
};

/**
 * Recomputes the description after the row allocations change. Manual text is
 * preserved verbatim; generated text always follows the current allocations,
 * including when every allocation was removed (which clears the cell).
 */
export const resolveDescriptionAfterAllocation = (
  current: ReceiptDescriptionState,
  billNumbers: Array<string | null | undefined>
): ReceiptDescriptionState => {
  if (!current.descriptionAuto) return { ...current };
  return { description: buildBillDescription(billNumbers), descriptionAuto: true };
};

/** Applies a manual edit. Clearing the cell hands control back to the system. */
export const resolveDescriptionAfterManualEdit = (value: string): ReceiptDescriptionState => ({
  description: value,
  descriptionAuto: cleanBillNumber(value) === '',
});

/**
 * Restores the description state when a saved voucher is opened. Empty cells
 * and previously generated text stay system managed; anything else is manual.
 */
export const resolveDescriptionOnLoad = (
  description: string | null | undefined,
  hasActiveAllocations: boolean
): ReceiptDescriptionState => {
  const text = description ?? '';
  const generated = hasActiveAllocations && isGeneratedBillDescription(text);
  return {
    description: text,
    descriptionAuto: generated || cleanBillNumber(text) === '',
  };
};